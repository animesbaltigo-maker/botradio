class _SafeParams(dict[str, object]):
    def __missing__(self, key: str) -> str:
        return "{" + key + "}"


def normalize_locale(value: str | None) -> str:
    if not value:
        return DEFAULT_LOCALE
    cleaned = value.strip().lower()
    if not cleaned:
        return DEFAULT_LOCALE
    short = cleaned.split("-", 1)[0].split("_", 1)[0]
    if short in SUPPORTED_LOCALES:
        return short
    return DEFAULT_LOCALE


def resolve_locale(preferred: str | None, telegram_language_code: str | None = None) -> str:
    if preferred:
        return normalize_locale(preferred)
    return normalize_locale(telegram_language_code)


def t(locale: str, key: str, **params: object) -> str:
    resolved_locale = normalize_locale(locale)
    template = (
        TRANSLATIONS.get(resolved_locale, {}).get(key)
        or TRANSLATIONS[DEFAULT_LOCALE].get(key)
        or key
    )
    if not params:
        return template
    return template.format_map(_SafeParams(params))


def escape_text(value: object) -> str:
    return escape(str(value), quote=True)


def strip_html(value: str) -> str:
    return re.sub(r"<[^>]+>", "", value)
